using System.Text.Json;
using MCAROC_Analysis.Data;
using MCAROC_Analysis.Data.Entities;
using MCAROC_Analysis.Services.AiUsage;
using Microsoft.EntityFrameworkCore;

namespace MCAROC_Analysis.Services.LitigationData;

public sealed record HindiSpelling(string Value, string Transliteration);

public sealed record AcronymExpansion(string Acronym, string FullForm);

public sealed record CompanyNameSuggestions(IReadOnlyList<HindiSpelling> HindiSpellings, IReadOnlyList<AcronymExpansion> Expansions)
{
    public static readonly CompanyNameSuggestions None = new([], []);
}

/// <summary>
/// The part of a company's litigation keywords that needs knowledge rather than rules (#489; owner: generated by AI, then checked), from one small call per
/// distinct name, cached for every later request and refresh:
/// <list type="bullet">
/// <item><b>Devanagari spellings</b> (भारत पेट्रोलियम), kept only if the transliteration sounds like the registered name or one of its written forms
/// (<see cref="NamePhoneticKey.SameName"/>): a made-up, translated or truncated name is refused.</item>
/// <item><b>Written-out acronyms</b> (HDFC = Housing Development Finance Corporation), kept only if the initials spell the acronym.</item>
/// </list>
/// Any failure gives no suggestions: the search goes ahead on the rule-made keywords and nobody has to step in.
/// </summary>
public sealed class CompanyNameSuggestionService(AppDbContext db, IServiceProvider services, ILogger<CompanyNameSuggestionService> logger)
{
    public const string PromptVersion = "name-suggestions-v1";
    public const string PromptMarker = "MCAROC COMPANY NAME SUGGESTIONS";
    public const int MaxSpellings = 3;
    private const string Language = "hi";
    private const int TimeoutSeconds = 60;

    /// <summary>Devanagari is stored as written, not escaped, so the audit columns can be read in the database.</summary>
    private static readonly JsonSerializerOptions Readable = new() { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    /// <param name="englishForms">The registered name's written forms (without the legal form, Corp for Corporation, ...): a Devanagari spelling may follow any of them.</param>
    public async Task<CompanyNameSuggestions> GetAsync(string? legalName, IReadOnlyCollection<string> englishForms, long? requestId, CancellationToken ct)
    {
        var nameKey = NameKey(legalName);
        if (nameKey.Length == 0) return CompanyNameSuggestions.None;

        var cached = await db.LitigationNameSpellings.AsNoTracking()
            .Where(s => s.NameKey == nameKey && s.Language == Language && s.PromptVersion == PromptVersion)
            .Select(s => new { s.SpellingsJson, s.ExpansionsJson }).FirstOrDefaultAsync(ct);
        if (cached is not null) return new(ParseSpellings(cached.SpellingsJson), ParseExpansions(cached.ExpansionsJson));

        ILitigationAiAnalysisClient client;
        try { client = services.GetRequiredService<ILitigationAiAnalysisClient>(); }
        catch (Exception ex)
        {
            logger.LogInformation("No name suggestions for {Name}: the AI client is not configured ({Error})", nameKey, ex.Message);
            return CompanyNameSuggestions.None;
        }

        LitigationAiCallResult result;
        using (AiUsageContext.Begin(requestId, AiUsagePurposes.KeywordSuggestion))
            result = await client.CallAsync(BuildPrompt(legalName!), TimeoutSeconds, ct);
        if (!result.Success)
        {
            // Not cached: a passing failure is tried again on the next search for this name.
            logger.LogWarning("Name suggestions for {Name} could not be generated: {Reason}", nameKey, result.FailureReason);
            return CompanyNameSuggestions.None;
        }

        var (rawSpellings, rawExpansions) = ReadAnswer(result.RawResponse);
        var (accepted, rejected) = CheckSpellings(legalName!, englishForms, rawSpellings);
        var (expansions, refusedExpansions) = CheckExpansions(legalName!, rawExpansions);
        rejected.AddRange(refusedExpansions);

        db.LitigationNameSpellings.Add(new LitigationNameSpelling
        {
            NameKey = nameKey, Language = Language, PromptVersion = PromptVersion, Model = VertexLitigationAiAnalysisClient.ModelId,
            SpellingsJson = JsonSerializer.Serialize(accepted.Select(a => a.Value), Readable),
            ExpansionsJson = expansions.Count == 0 ? null : JsonSerializer.Serialize(expansions.Select(e => new { acronym = e.Acronym, fullForm = e.FullForm }), Readable),
            RejectedJson = rejected.Count == 0 ? null : JsonSerializer.Serialize(rejected.Select(r => new { spelling = r.Spelling, reason = r.Reason }), Readable),
            CreatedUtc = DateTime.UtcNow
        });
        try { await db.SaveChangesAsync(ct); }
        catch (DbUpdateException)
        {
            // Another search for the same name stored its result first: either answer is fine, keep ours for this search.
            db.ChangeTracker.Clear();
        }
        if (rejected.Count > 0)
            logger.LogInformation("Name suggestions for {Name}: {Accepted} spellings and {Expansions} expansions kept, {Rejected} refused by the checks ({Reasons})",
                nameKey, accepted.Count, expansions.Count, rejected.Count, string.Join("; ", rejected.Select(r => $"{r.Spelling}: {r.Reason}")));
        return new(accepted, expansions);
    }

    /// <summary>The spelling back-check: Devanagari, and sounding like the registered name or one of its written forms. At most <see cref="MaxSpellings"/>.</summary>
    internal static (List<HindiSpelling> Accepted, List<(string Spelling, string Reason)> Rejected) CheckSpellings(
        string legalName, IEnumerable<string> englishForms, IEnumerable<string> candidates)
    {
        var forms = new[] { legalName }.Concat(englishForms).Where(f => !string.IsNullOrWhiteSpace(f)).ToList();
        var accepted = new List<HindiSpelling>();
        var rejected = new List<(string, string)>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var raw in candidates)
        {
            var spelling = raw?.Trim() ?? "";
            if (spelling.Length == 0 || !seen.Add(spelling)) continue;
            var transliteration = NamePhoneticKey.Transliterate(spelling);
            if (!NamePhoneticKey.IsDevanagari(spelling)) rejected.Add((spelling, "not written in Devanagari"));
            else if (!forms.Any(f => NamePhoneticKey.SameName(spelling, f)))
                rejected.Add((spelling, $"reads as \"{transliteration}\", which does not sound like the registered name"));
            else if (accepted.Count >= MaxSpellings) rejected.Add((spelling, "more than the allowed number of spellings"));
            else accepted.Add(new HindiSpelling(spelling, transliteration));
        }
        return (accepted, rejected);
    }

    /// <summary>An expansion is kept only for an acronym that is a word of the name and only when its initials spell that acronym.</summary>
    internal static (List<AcronymExpansion> Accepted, List<(string Spelling, string Reason)> Rejected) CheckExpansions(
        string legalName, IEnumerable<AcronymExpansion> candidates)
    {
        var nameWords = legalName.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(w => w.Trim('.', ',')).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var accepted = new List<AcronymExpansion>();
        var rejected = new List<(string, string)>();
        foreach (var c in candidates)
        {
            var acronym = c.Acronym?.Trim() ?? "";
            var full = c.FullForm?.Trim() ?? "";
            if (acronym.Length == 0 || full.Length == 0) continue;
            if (!nameWords.Contains(acronym)) rejected.Add((full, $"\"{acronym}\" is not a word of the name"));
            else if (!NameFormVariants.ExpandsTo(acronym, full)) rejected.Add((full, $"its initials do not spell \"{acronym}\""));
            else if (accepted.All(a => !a.FullForm.Equals(full, StringComparison.OrdinalIgnoreCase))) accepted.Add(new AcronymExpansion(acronym.ToUpperInvariant(), full));
        }
        return (accepted, rejected);
    }

    internal static string BuildPrompt(string legalName) =>
        $$"""
        {{PromptMarker}} ({{PromptVersion}})
        Indian court records sometimes write a company's name in Hindi (Devanagari script) or write out an acronym that is part of its name.
        For the company name below:
        1. "spellings": up to {{MaxSpellings}} ways to write the name in Devanagari as a court clerk would. Transliterate every word by its sound.
           Never translate the meaning of a word, never abbreviate, never add words. Give the full name with its legal form in Devanagari
           (for example प्राइवेट लिमिटेड or लिमिटेड), the name without the legal form, and the short name without words such as Corporation or Company.
        2. "expansions": for each acronym that is a word of the name (for example HDFC), its widely known full form, only if you are certain.
           Otherwise an empty list.
        Answer with JSON only: {"spellings": ["..."], "expansions": [{"acronym": "...", "full_form": "..."}]}

        Company name: {{legalName.Trim()}}
        """;

    internal static (IReadOnlyList<string> Spellings, IReadOnlyList<AcronymExpansion> Expansions) ReadAnswer(string raw)
    {
        try
        {
            using var doc = JsonDocument.Parse(raw);
            var root = doc.RootElement;
            if (root.ValueKind == JsonValueKind.Array && root.GetArrayLength() == 1) root = root[0];
            if (root.ValueKind != JsonValueKind.Object) return ([], []);
            var spellings = root.TryGetProperty("spellings", out var s) && s.ValueKind == JsonValueKind.Array
                ? s.EnumerateArray().Where(e => e.ValueKind == JsonValueKind.String).Select(e => e.GetString()!).ToList() : [];
            var expansions = root.TryGetProperty("expansions", out var x) && x.ValueKind == JsonValueKind.Array
                ? x.EnumerateArray().Where(e => e.ValueKind == JsonValueKind.Object)
                    .Select(e => new AcronymExpansion(Str(e, "acronym"), Str(e, "full_form") is { Length: > 0 } f ? f : Str(e, "fullForm"))).ToList()
                : [];
            return (spellings, expansions);
        }
        catch (JsonException) { return ([], []); }

        static string Str(JsonElement e, string name) => e.TryGetProperty(name, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() ?? "" : "";
    }

    private static IReadOnlyList<HindiSpelling> ParseSpellings(string json)
    {
        try { return (JsonSerializer.Deserialize<List<string>>(json) ?? []).Select(s => new HindiSpelling(s, NamePhoneticKey.Transliterate(s))).ToList(); }
        catch (JsonException) { return []; }
    }

    private static IReadOnlyList<AcronymExpansion> ParseExpansions(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return [];
        try
        {
            using var doc = JsonDocument.Parse(json);
            return doc.RootElement.EnumerateArray()
                .Select(e => new AcronymExpansion(e.GetProperty("acronym").GetString() ?? "", e.GetProperty("fullForm").GetString() ?? "")).ToList();
        }
        catch (Exception ex) when (ex is JsonException or KeyNotFoundException or InvalidOperationException) { return []; }
    }

    internal static string NameKey(string? name) =>
        string.IsNullOrWhiteSpace(name) ? string.Empty : string.Join(' ', name.Trim().ToUpperInvariant().Split(' ', StringSplitOptions.RemoveEmptyEntries));
}
